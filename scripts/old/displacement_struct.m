    'name', '', 'dx', [], 'dy', [], 'total', [], 'yaw', [], ...
    'rms', [], 'overlap', [], 'start_time', '', 'end_time', ''), n_passes, 1);

% ─── Compute dx, dy, total, yaw per pass and fill struct array ──────────
for i = 1:n_passes
    T      = T_all{i};
    T_inv  = inv(T);
    pMoved = T_inv * ref;

    dx    = pMoved(1) - ref(1);
    dy    = pMoved(2) - ref(2);
    total = sqrt(dx^2 + dy^2);
    yaw   = atan2d(T(2,1), T(1,1));

    passCorrection(i).name       = passNames{i};
    passCorrection(i).dx          = dx;
    passCorrection(i).dy          = dy;
    passCorrection(i).total       = total;
    passCorrection(i).yaw         = yaw;
    passCorrection(i).rms         = rms_all(i);
    passCorrection(i).overlap     = overlap_all(i);
    passCorrection(i).start_time  = startTimes{i};
    passCorrection(i).end_time    = endTimes{i};
end

